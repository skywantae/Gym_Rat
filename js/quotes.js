export class MotivationalQuotesService {
    static currentIndex = -1;

    /**
     * 직전 표시된 문구와 중복되지 않는 새로운 문구를 무작위 추첨합니다.
     */
    static getRandomQuote() {
        if (!MOTIVATIONAL_QUOTES || MOTIVATIONAL_QUOTES.length === 0) return null;
        if (MOTIVATIONAL_QUOTES.length === 1) {
            this.currentIndex = 0;
            return MOTIVATIONAL_QUOTES[0];
        }

        let nextIndex;
        do {
            nextIndex = Math.floor(Math.random() * MOTIVATIONAL_QUOTES.length);
        } while (nextIndex === this.currentIndex);

        this.currentIndex = nextIndex;
        return MOTIVATIONAL_QUOTES[nextIndex];
    }

    /**
     * 대시보드 내 운동 자극 문구 영역을 부드러운 페이드 효과와 함께 갱신합니다.
     */
    static renderMotivationalQuote() {
        const textEl = document.getElementById("motivational-quote-text");
        const subEl = document.getElementById("motivational-quote-sub");
        const typeEl = document.getElementById("quote-category-tag");
        if (!textEl) return;

        const item = this.getRandomQuote();
        if (!item) return;

        textEl.style.opacity = "0";
        if (subEl) subEl.style.opacity = "0";

        setTimeout(() => {
            textEl.textContent = `"${item.quote}"`;
            if (subEl) subEl.textContent = item.sub;
            if (typeEl) {
                typeEl.textContent = item.type;
                typeEl.className = `quote-category-tag badge-${item.badgeColor}`;
            }
            textEl.style.opacity = "1";
            if (subEl) subEl.style.opacity = "1";
        }, 120);
    }
}
